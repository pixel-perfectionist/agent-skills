#!/usr/bin/env python3
"""Validate, post and check pull request review comments from a plan file.

  validate --plan plan.json
      Check inline anchors against the PR diff at the current head, look for a
      pending review and for comments already on GitHub, and lint the voice.
  post --plan plan.json [--min-delay 180] [--max-delay 420] [--dry-run]
      Post the comments in order, one at a time, waiting a random delay
      between them. Progress is kept in posted.json next to the plan.
  status --plan plan.json
      Confirm that every posted comment exists on GitHub.

Plan format:
  {"repo": "owner/name",
   "comments": [{"key": "...", "pr": 77, "kind": "pr" | "inline", "body": "...",
                 "path": "...", "line": 12, "start_line": 10, "commit_id": "..."}]}

Uses the GitHub CLI (`gh`) as the signed-in user. Standard library only.
"""

from __future__ import annotations

import argparse
import base64
import json
import os
import random
import re
import subprocess
import sys
import time
from datetime import datetime
from urllib.parse import quote

DEFAULT_MIN_DELAY_SECONDS = 180  # 3 minutes
DEFAULT_MAX_DELAY_SECONDS = 420  # 7 minutes

HUNK_HEADER = re.compile(r"^@@ -\d+(?:,\d+)? \+(\d+)(?:,(\d+))? @@", re.M)
CODE = re.compile(r"```.*?```|`[^`\n]*`", re.S)
EMOJI = re.compile("[\U0001F300-\U0001FAFF\u2600-\u27BF\u2B50\u2B55\u2705\u274C\u2753\u2757]")
THANKS = re.compile(r"\bthank(s| you)\b", re.I)

# Prose only: code spans and blocks are stripped before these run.
VOICE_ERRORS = [
    (re.compile("\u2014"), "em dash; use a period or a comma"),
    (re.compile(r"\s\u2013\s"), "en dash used as a dash; use a period or a comma"),
    (re.compile(r"^\s{0,3}#{1,6}\s", re.M), "heading"),
    (re.compile(r"\*\*"), "bold"),
    (
        re.compile(
            r"\bas an ai\b|\blanguage model\b|\bllm\b|\bchatgpt\b|\bclaude\b|"
            r"\bgpt-?\d|\bgenerated by\b|\bai[- ]generated\b|\bai[- ]assisted\b",
            re.I,
        ),
        "mentions AI or a model",
    ),
]
VOICE_WARNINGS = [
    (
        re.compile(
            r"\bi noticed\b|\bit seems\b|\bit looks like\b|\bgreat (job|work)\b|"
            r"\bnice work\b|\blet me know\b|\bhope this helps\b|\bfeel free\b|"
            r"\bjust a suggestion\b|\byou might want to\b|\bconsider refactoring\b|"
            r"\boverall,",
            re.I,
        ),
        "filler phrase",
    ),
    (
        re.compile(
            r"\bensure[sd]?\b|\brobust(ly)?\b|\bseamless(ly)?\b|\bleverag(e|es|ing)\b|"
            r"\bdelve\b|\bcrucial\b|\bcomprehensive\b|\butiliz(e|es|ing)\b",
            re.I,
        ),
        "buzzword",
    ),
    (re.compile(r"\bcopilot\b|\bAI\b|\bagent\b", re.I), "mentions Copilot, AI or an agent; keep only if it is about the code"),
]


def log(message: str) -> None:
    print(f"{datetime.now().strftime('%H:%M:%S')} {message}", flush=True)


def run_gh(args: list[str], payload: dict | None = None, raw: bool = False):
    proc = subprocess.run(
        ["gh", "api", *args],
        input=None if payload is None else json.dumps(payload),
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:
        raise RuntimeError((proc.stderr or proc.stdout).strip())
    if raw:
        return proc.stdout
    out = proc.stdout.strip()
    return json.loads(out) if out else None


def gh_list(path: str) -> list:
    """All pages of a list endpoint, merged."""
    text = run_gh(["--paginate", path], raw=True).strip()
    decoder, items, index = json.JSONDecoder(), [], 0
    while index < len(text):
        page, end = decoder.raw_decode(text, index)
        items.extend(page if isinstance(page, list) else [page])
        index = end
        while index < len(text) and text[index].isspace():
            index += 1
    return items


def normalize(body: str) -> str:
    return " ".join(body.split())


def load_plan(path: str) -> tuple[str, list[dict]]:
    with open(path, encoding="utf-8") as handle:
        plan = json.load(handle)
    repo, comments = plan.get("repo"), plan.get("comments")
    if not isinstance(repo, str) or repo.count("/") != 1:
        sys.exit('plan: "repo" must be "owner/name"')
    if not isinstance(comments, list) or not comments:
        sys.exit('plan: "comments" must be a non-empty list')
    seen = set()
    for index, comment in enumerate(comments):
        where = f"plan: comment {index + 1}"
        key = comment.get("key")
        if not isinstance(key, str) or not key:
            sys.exit(f'{where}: "key" is required')
        if key in seen:
            sys.exit(f"{where}: duplicate key {key!r}")
        seen.add(key)
        if comment.get("kind") not in ("pr", "inline"):
            sys.exit(f'{where} ({key}): "kind" must be "pr" or "inline"')
        if not isinstance(comment.get("pr"), int):
            sys.exit(f'{where} ({key}): "pr" must be a number')
        if not isinstance(comment.get("body"), str) or not comment["body"].strip():
            sys.exit(f'{where} ({key}): "body" is required')
        if comment["kind"] == "inline":
            if not isinstance(comment.get("path"), str) or not isinstance(comment.get("line"), int):
                sys.exit(f'{where} ({key}): inline comments need "path" and "line"')
            if not isinstance(comment.get("commit_id"), str) or len(comment["commit_id"]) != 40:
                sys.exit(f'{where} ({key}): inline comments need the full 40-character "commit_id"')
            start = comment.get("start_line")
            if start is not None and (not isinstance(start, int) or start > comment["line"]):
                sys.exit(f'{where} ({key}): "start_line" must be a number no greater than "line"')
    return repo, comments


def state_path_for(plan_path: str) -> str:
    return os.path.join(os.path.dirname(os.path.abspath(plan_path)), "posted.json")


def load_state(plan_path: str) -> dict:
    path = state_path_for(plan_path)
    if not os.path.exists(path):
        return {}
    with open(path, encoding="utf-8") as handle:
        return json.load(handle)


def save_state(plan_path: str, state: dict) -> None:
    with open(state_path_for(plan_path), "w", encoding="utf-8") as handle:
        json.dump(state, handle, indent=1)


def my_comments_on_pr(repo: str, pr: int, login: str) -> dict[str, dict]:
    """The signed-in user's comments on a PR, by normalized body."""
    found = {}
    for kind, path in (("pr", f"repos/{repo}/issues/{pr}/comments?per_page=100"),
                       ("inline", f"repos/{repo}/pulls/{pr}/comments?per_page=100")):
        for item in gh_list(path):
            if item.get("user", {}).get("login") == login:
                found[normalize(item.get("body") or "")] = {
                    "pr": pr, "kind": kind, "id": item["id"], "url": item["html_url"]}
    return found


def lint_voice(comments: list[dict]) -> tuple[list[str], list[str]]:
    errors, warnings = [], []
    for comment in comments:
        prose = CODE.sub("", comment["body"])
        for pattern, label in VOICE_ERRORS:
            if pattern.search(prose):
                errors.append(f"{comment['key']}: {label}")
        if EMOJI.search(prose):
            errors.append(f"{comment['key']}: emoji")
        for pattern, label in VOICE_WARNINGS:
            match = pattern.search(prose)
            if match:
                warnings.append(f"{comment['key']}: {label} ({match.group(0)!r})")
    thanked = [c["key"] for c in comments if THANKS.search(CODE.sub("", c["body"]))]
    if len(thanked) > 1:
        errors.append(f"thanks appears in {len(thanked)} comments ({', '.join(thanked)}); keep it once, in the first")
    elif thanked and thanked[0] != comments[0]["key"]:
        warnings.append(f"{thanked[0]}: the only thank-you is not in the first comment posted")
    return errors, warnings


def in_diff(patch: str, start: int, end: int) -> bool:
    for match in HUNK_HEADER.finditer(patch):
        first = int(match.group(1))
        last = first + int(match.group(2) or 1) - 1
        if first <= start and end <= last:
            return True
    return False


def source_line(repo: str, path: str, commit: str, line: int) -> str:
    """The anchored line, so a wrong number is easy to spot. Display only."""
    try:
        data = run_gh([f"repos/{repo}/contents/{quote(path)}?ref={commit}"])
    except RuntimeError:
        return "(could not read)"
    if data.get("encoding") != "base64":
        return "(file too large to show)"
    lines = base64.b64decode(data["content"]).decode("utf-8", "replace").splitlines()
    return lines[line - 1].strip() if 0 < line <= len(lines) else "(line out of range)"


def check_plan(repo: str, comments: list[dict], login: str, state: dict,
               show=None, duplicates_are_errors: bool = True) -> tuple[list[str], list[str]]:
    """Everything that must hold before posting. `show`, when given, receives display lines.

    `post` passes `duplicates_are_errors=False`: text that is already on the PR
    (an earlier run that lost its posted.json) is skipped and recorded there.
    """
    errors, warnings = lint_voice(comments)
    for pr in dict.fromkeys(c["pr"] for c in comments):
        info = run_gh([f"repos/{repo}/pulls/{pr}"])
        head = info["head"]["sha"]
        if show:
            show(f"#{pr} {info['state']} head {head[:7]} by {info['user']['login']}: {info['title']}")
        if info["state"] != "open":
            errors.append(f"#{pr} is {info['state']}")
        pending = [r for r in gh_list(f"repos/{repo}/pulls/{pr}/reviews?per_page=100")
                   if r.get("state") == "PENDING" and r.get("user", {}).get("login") == login]
        if pending:
            errors.append(f"#{pr}: {login} has a pending review; submit or discard it first")
        existing = my_comments_on_pr(repo, pr, login)
        patches = {f["filename"]: f.get("patch") for f in gh_list(f"repos/{repo}/pulls/{pr}/files?per_page=100")}
        for comment in (c for c in comments if c["pr"] == pr):
            key = comment["key"]
            if key in state:
                warnings.append(f"{key}: already posted according to posted.json; post will skip it")
                continue
            if normalize(comment["body"]) in existing:
                (errors if duplicates_are_errors else warnings).append(
                    f"{key}: the same text is already on #{pr}")
            if comment["kind"] == "pr":
                if show:
                    show(f"  {key}: PR comment")
                continue
            if comment["commit_id"] != head:
                errors.append(f"{key}: planned for {comment['commit_id'][:7]}, but #{pr} head is {head[:7]}")
            patch = patches.get(comment["path"])
            start = comment.get("start_line") or comment["line"]
            if patch is None:
                errors.append(f"{key}: {comment['path']} is not in the diff of #{pr}, or GitHub shows no patch for it")
            elif not in_diff(patch, start, comment["line"]):
                errors.append(f"{key}: {comment['path']}:{comment['line']} is outside the diff hunks of #{pr}")
            if show:
                show(f"  {key}: {comment['path']}:{comment['line']}  | "
                     f"{source_line(repo, comment['path'], comment['commit_id'], comment['line'])[:100]}")
    return errors, warnings


def validate(args: argparse.Namespace) -> int:
    repo, comments = load_plan(args.plan)
    login = run_gh(["user"])["login"]
    errors, warnings = check_plan(repo, comments, login, load_state(args.plan), show=print)
    gaps = max(len(comments) - 1, 0)
    print(f"\n{len(comments)} comments as {login}; about {gaps * (args.min_delay + args.max_delay) / 2 / 60:.0f} min "
          f"({gaps * args.min_delay / 60:.0f}-{gaps * args.max_delay / 60:.0f} min) with "
          f"{args.min_delay / 60:g}-{args.max_delay / 60:g} min gaps")
    for warning in warnings:
        print(f"WARNING {warning}")
    for error in errors:
        print(f"ERROR {error}")
    print("OK" if not errors else f"{len(errors)} error(s)")
    return 1 if errors else 0


def post(args: argparse.Namespace) -> int:
    repo, comments = load_plan(args.plan)
    if args.min_delay > args.max_delay:
        sys.exit("--min-delay must not exceed --max-delay")
    login = run_gh(["user"])["login"]
    state = load_state(args.plan)
    errors, _ = check_plan(repo, comments, login, state, duplicates_are_errors=False)
    if errors:
        for error in errors:
            log(f"ERROR {error}")
        log("nothing posted; fix the plan and run validate")
        return 1
    log(f"{'dry run: ' if args.dry_run else ''}{len(comments)} comments to {repo} as {login}")
    # The first comment of a fresh run goes out at once. A rerun waits before
    # its first new comment too, so it does not land right after the last one.
    post_now = not state
    failures = 0
    for comment in comments:
        key, pr = comment["key"], comment["pr"]
        if key in state:
            log(f"skip {key}: already posted")
            continue
        if not post_now:
            delay = random.uniform(args.min_delay, args.max_delay)
            log(f"waiting {delay / 60:.1f} min before {key}")
            time.sleep(delay)
        post_now = False
        try:
            if comment["kind"] == "inline":
                head = run_gh([f"repos/{repo}/pulls/{pr}"])["head"]["sha"]
                if head != comment["commit_id"]:
                    log(f"STOP: #{pr} head moved to {head[:7]} (planned {comment['commit_id'][:7]}); "
                        f"nothing from {key} on was posted")
                    return 2
            existing = my_comments_on_pr(repo, pr, login).get(normalize(comment["body"]))
            if existing:
                if not args.dry_run:
                    state[key] = existing
                    save_state(args.plan, state)
                log(f"skip {key}: the same text is already on #{pr} ({existing['url']})")
                continue
            if args.dry_run:
                log(f"would post {key} on #{pr}")
                continue
            if comment["kind"] == "inline":
                payload = {"body": comment["body"], "commit_id": comment["commit_id"],
                           "path": comment["path"], "line": comment["line"], "side": "RIGHT"}
                if comment.get("start_line") and comment["start_line"] != comment["line"]:
                    payload.update(start_line=comment["start_line"], start_side="RIGHT")
                result = run_gh(["--method", "POST", f"repos/{repo}/pulls/{pr}/comments", "--input", "-"], payload)
            else:
                result = run_gh(["--method", "POST", f"repos/{repo}/issues/{pr}/comments", "--input", "-"],
                                {"body": comment["body"]})
        except RuntimeError as error:
            failures += 1
            log(f"FAILED {key}: {error}")
            continue
        state[key] = {"pr": pr, "kind": comment["kind"], "id": result["id"], "url": result["html_url"]}
        save_state(args.plan, state)
        log(f"posted {key}: {result['html_url']}")
    log(f"done: {len(state)}/{len(comments)} posted, {failures} failed")
    return 1 if failures else 0


def status(args: argparse.Namespace) -> int:
    repo, comments = load_plan(args.plan)
    state = load_state(args.plan)
    missing = 0
    for comment in comments:
        entry = state.get(comment["key"])
        if not entry:
            missing += 1
            print(f"NOT POSTED {comment['key']}")
            continue
        path = (f"repos/{repo}/pulls/comments/{entry['id']}" if entry["kind"] == "inline"
                else f"repos/{repo}/issues/comments/{entry['id']}")
        try:
            item = run_gh([path])
        except RuntimeError as error:
            missing += 1
            print(f"MISSING {comment['key']}: {error}")
            continue
        where = f"{item['path']}:{item.get('line')}" if entry["kind"] == "inline" else "PR comment"
        print(f"OK {comment['key']} #{entry['pr']} {where} {item['created_at']} by {item['user']['login']} {entry['url']}")
    return 1 if missing else 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    for name in ("validate", "post", "status"):
        command = commands.add_parser(name)
        command.add_argument("--plan", required=True)
        if name in ("validate", "post"):
            command.add_argument("--min-delay", type=int, default=DEFAULT_MIN_DELAY_SECONDS, help="seconds")
            command.add_argument("--max-delay", type=int, default=DEFAULT_MAX_DELAY_SECONDS, help="seconds")
        if name == "post":
            command.add_argument("--dry-run", action="store_true", help="do everything except posting")
    args = parser.parse_args()
    return {"validate": validate, "post": post, "status": status}[args.command](args)


if __name__ == "__main__":
    sys.exit(main())
